import jax.numpy as jnp

from operators.second_derivative import second_derivative


# ============================================================
# ДВУМЕРНЫЙ ВЕКТОРНЫЙ ЛАПЛАСИАН
#
# u_ext[..., 0] = u
# u_ext[..., 1] = v
#
# u_ext уже содержит фиктивные ячейки.
#
# Δu = u_xx + u_yy
# Δv = v_xx + v_yy
# ============================================================

def vector_laplacian_2d(
    u_ext,
    dx,
    dy,
    ng=4,
):

    result = []

    for component in range(2):

        q = u_ext[..., component]

        # ----------------------------------------------------
        # d²/dx²
        #
        # second_derivative удаляет фиктивные ячейки только вдоль
        # оси дифференцирования.
        #
        # Поэтому фиктивные ячейки вдоль y сохраняются.
        # ----------------------------------------------------

        dxx = second_derivative(
            q,
            dx,
            axis=0,
            ng=ng,
        )

        # dxx: (nx, ny + 2*ng)
        # удаляем фиктивные ячейки вдоль y
        dxx = dxx[
            :,
            ng:-ng,
        ]

        # ----------------------------------------------------
        # d²/dy²
        # ----------------------------------------------------

        dyy = second_derivative(
            q,
            dy,
            axis=1,
            ng=ng,
        )

        # dyy: (nx + 2*ng, ny)
        # удаляем фиктивные ячейки вдоль x
        dyy = dyy[
            ng:-ng,
            :,
        ]

        # ----------------------------------------------------
        # Теперь оба массива имеют форму (nx, ny)
        # ----------------------------------------------------

        result.append(
            dxx + dyy
        )

    return jnp.stack(
        result,
        axis=-1,
    )


# ============================================================
# ТРЁХМЕРНЫЙ ВЕКТОРНЫЙ ЛАПЛАСИАН
#
# u_ext[..., 0] = u
# u_ext[..., 1] = v
# u_ext[..., 2] = w
#
# u_ext уже содержит фиктивные ячейки.
#
# Δu = u_xx + u_yy + u_zz
# ============================================================

def vector_laplacian_3d(
    u_ext,
    dx,
    dy,
    dz,
    ng=4,
):

    result = []

    for component in range(3):

        q = u_ext[..., component]

        # ----------------------------------------------------
        # d²/dx²
        # ----------------------------------------------------

        dxx = second_derivative(
            q,
            dx,
            axis=0,
            ng=ng,
        )

        # dxx:
        # (nx, ny + 2*ng, nz + 2*ng)
        #
        # удаляем фиктивные ячейки вдоль y и z

        dxx = dxx[
            :,
            ng:-ng,
            ng:-ng,
        ]

        # ----------------------------------------------------
        # d²/dy²
        # ----------------------------------------------------

        dyy = second_derivative(
            q,
            dy,
            axis=1,
            ng=ng,
        )

        # dyy:
        # (nx + 2*ng, ny, nz + 2*ng)
        #
        # удаляем фиктивные ячейки вдоль x и z

        dyy = dyy[
            ng:-ng,
            :,
            ng:-ng,
        ]

        # ----------------------------------------------------
        # d²/dz²
        # ----------------------------------------------------

        dzz = second_derivative(
            q,
            dz,
            axis=2,
            ng=ng,
        )

        # dzz:
        # (nx + 2*ng, ny + 2*ng, nz)
        #
        # удаляем фиктивные ячейки вдоль x и y

        dzz = dzz[
            ng:-ng,
            ng:-ng,
            :,
        ]

        # ----------------------------------------------------
        # Теперь все три массива имеют форму:
        #
        # (nx, ny, nz)
        # ----------------------------------------------------

        result.append(
            dxx + dyy + dzz
        )

    return jnp.stack(
        result,
        axis=-1,
    )
